import assert from 'node:assert/strict';
import { mkdtemp,readFile,rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {drizzle} from 'drizzle-orm/d1';
import {sqliteTable,text} from 'drizzle-orm/sqlite-core';
import {openStorage} from '../selfhost/storage.mjs';
const temporary=await mkdtemp(path.join(os.tmpdir(),'nexus-storage-test-'));
const migrationsDirectory=fileURLToPath(new URL('../drizzle',import.meta.url));
let storage;
try{
 storage=openStorage({dataDirectory:temporary,migrationsDirectory});
 let {DB,BUCKET}=storage;
 const journal=JSON.parse(await readFile(path.join(migrationsDirectory,'meta','_journal.json'),'utf8'));
 assert.equal((await DB.prepare('SELECT count(*) AS n FROM _nexus_migrations').first()).n,journal.entries.length);
 const insert=()=>DB.prepare("INSERT INTO notes(id,owner,title,content,updated_at) VALUES(?,?,?,?,?)").bind('n1','owner1','title','content','2026-10-26');
 await assert.rejects(DB.batch([insert(),insert()]));
 assert.equal((await DB.prepare('SELECT count(*) AS n FROM notes').first()).n,0,'transaction must roll back');
 await DB.batch([insert(),DB.prepare("UPDATE notes SET title=? WHERE id=? RETURNING id").bind('edited','n1')]);
 assert.deepEqual(await DB.prepare('SELECT id,title FROM notes').raw(),[['n1','edited']]);
 const notes=sqliteTable('notes',{id:text().primaryKey(),owner:text(),title:text(),content:text(),updatedAt:text('updated_at')});
 const orm=drizzle(DB);
 assert.equal((await orm.select().from(notes))[0].title,'edited');
 const batch=await orm.batch([orm.update(notes).set({title:'orm'}).returning({id:notes.id}),orm.select().from(notes)]);
 assert.equal(batch[1][0].title,'orm');
 await BUCKET.put('snapshots/owner1/2026-10-26.json',JSON.stringify({tasks:[1]}),{onlyIf:{etagDoesNotMatch:'*'}});
 assert.equal(await BUCKET.put('snapshots/owner1/2026-10-26.json','overwritten',{onlyIf:{etagDoesNotMatch:'*'}}),null);
 assert.deepEqual(await (await BUCKET.get('snapshots/owner1/2026-10-26.json')).json(),{tasks:[1]});
 assert.equal((await BUCKET.list({prefix:'snapshots/owner2/'})).objects.length,0);
 await assert.rejects(BUCKET.get('../escape'));
 await assert.rejects(BUCKET.put('C:/escape','bad'));
 await BUCKET.put('maintenance/latest.json','{"ok":false}');
 await BUCKET.put('maintenance/latest.json','{"ok":true}');
 storage.close();storage=openStorage({dataDirectory:temporary,migrationsDirectory});
 assert.equal((await storage.DB.prepare('SELECT title FROM notes').first()).title,'orm');
 assert.equal((await (await storage.BUCKET.get('maintenance/latest.json')).json()).ok,true);
 await storage.BUCKET.delete('snapshots/owner1/2026-10-26.json');
 assert.equal(await storage.BUCKET.head('snapshots/owner1/2026-10-26.json'),null);
 console.log('PASS: migrations, atomic rollback, Drizzle queries/batch, private prefixes, exclusive snapshots, traversal rejection, persistence and deletion.');
}finally{storage?.close();await rm(temporary,{recursive:true,force:true});}
